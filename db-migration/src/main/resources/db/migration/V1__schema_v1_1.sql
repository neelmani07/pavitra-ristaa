CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES "user" (id),
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    device_name VARCHAR(255),
