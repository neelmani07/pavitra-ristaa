CREATE TABLE match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    user_a_id BIGINT NOT NULL REFERENCES "user" (id),
    user_b_id BIGINT NOT NULL REFERENCES "user" (id),
    relationship_mode_id BIGINT NOT NULL REFERENCES relationship_mode (id),
    source_interest_id BIGINT REFERENCES interest (id),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    matched_at TIMESTAMPTZ NOT NULL,
    unmatched_at TIMESTAMPTZ,
    CONSTRAINT chk_match_not_self CHECK (user_a_id <> user_b_id),
    CONSTRAINT chk_match_status CHECK (status IN ('ACTIVE', 'UNMATCHED')),
    CONSTRAINT chk_match_user_order CHECK (user_a_id < user_b_id),
    CONSTRAINT uq_match_pair_mode UNIQUE (user_a_id, user_b_id, relationship_mode_id)
);

CREATE INDEX idx_match_user_a ON match (user_a_id);
CREATE INDEX idx_match_user_b ON match (user_b_id);

