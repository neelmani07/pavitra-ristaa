CREATE UNIQUE INDEX uq_payment_provider_id ON payment (provider, provider_payment_id)
    WHERE provider_payment_id IS NOT NULL;
CREATE INDEX idx_payment_user_created ON payment (user_id, created_at);
CREATE INDEX idx_payment_status ON payment (status);

CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES "user" (id),
    subscription_id BIGINT REFERENCES subscription (id),
    payment_id BIGINT REFERENCES payment (id),
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    amount NUMERIC(12, 2) NOT NULL,
    tax_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(12, 2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    status VARCHAR(30) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_invoice_status CHECK (status IN ('ISSUED', 'PAID', 'VOID'))
);

CREATE TABLE media_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_file_id BIGINT NOT NULL REFERENCES media_file (id),
    user_id BIGINT NOT NULL REFERENCES "user" (id),
    access_type VARCHAR(30) NOT NULL,
    granted_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    CONSTRAINT uq_media_access UNIQUE (media_file_id, user_id, access_type),
    CONSTRAINT chk_media_access_type CHECK (access_type IN ('VIEW', 'DOWNLOAD'))
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES "user" (id),
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100),
    entity_id BIGINT,
    ip_address INET,
    metadata JSONB,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_audit_log_actor ON audit_log (actor_user_id, created_at);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_created ON audit_log (created_at);

CREATE TABLE support_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES "user" (id),
    category VARCHAR(50) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    priority VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    assigned_to BIGINT REFERENCES "user" (id),
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_ticket_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    CONSTRAINT chk_ticket_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT'))
);

CREATE INDEX idx_support_ticket_user_status ON support_ticket (user_id, status);
CREATE INDEX idx_support_ticket_assigned ON support_ticket (assigned_to, status);

CREATE TABLE moderation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    target_user_id BIGINT REFERENCES "user" (id),
    target_profile_id BIGINT REFERENCES user_profile (id),
    target_media_id BIGINT REFERENCES media_file (id),
    target_message_id BIGINT REFERENCES message (id),
    source_report_id BIGINT REFERENCES report (id),
    action VARCHAR(50) NOT NULL,
    reason TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    moderator_user_id BIGINT REFERENCES "user" (id),
    created_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_moderation_action CHECK (action IN ('WARN', 'HIDE', 'SUSPEND', 'BLOCK', 'REMOVE')),
    CONSTRAINT chk_moderation_status CHECK (status IN ('OPEN', 'RESOLVED'))
);

CREATE INDEX idx_moderation_target_user ON moderation (target_user_id, status);
CREATE INDEX idx_moderation_status_created ON moderation (status, created_at);

CREATE TABLE system_setting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(150) NOT NULL UNIQUE,
    setting_value TEXT,
    value_type VARCHAR(30) NOT NULL,
    description VARCHAR(255),
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by BIGINT REFERENCES "user" (id),
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_setting_value_type CHECK (value_type IN ('STRING', 'INTEGER', 'BOOLEAN', 'JSON'))
);
